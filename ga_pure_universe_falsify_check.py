import numpy as np
import sympy as sp
from ga_core import ok

lam = sp.symbols('lambda', positive=True)

# PU1 'pure GA universe = O(2,4)' with gravity: under g -> lam^2 g in 4D, sqrt(-g) R -> lam^2 sqrt(-g) R, so the Einstein-Hilbert term
#     M_P^2 sqrt(-g) R has K weight 2 -- like mu^2 |H|^2. With gravity on, K is broken by M_P itself and the vacuum is Minkowski with
#     Killing algebra of dimension 10 (Poincare); the 15 conformal Killing vectors are a symmetry of the massless MATTER equations only.
#     NARROWED: O(2,4) is the symmetry of the matter sector at its symmetric points; the geometry needs M_P -> infinity (gravity decoupled),
#     which is a limit of a dimensional scale, not a symmetric point of a dimensionless number.
n = 4
w_sqrtg, w_R = n, -2
w_EH = w_sqrtg + w_R
ok(f"PU1 NARROWED: weight of sqrt(-g) R under g -> lam^2 g is lam^{w_EH}; Einstein-Hilbert breaks K like mu^2; Minkowski isometries "
   f"{n * (n + 1) // 2} < conformal {(n + 1) * (n + 2) // 2}", w_EH == 2)

# PU2 'K-protected small numbers are unnatural because K is anomalous' (NF4) is refuted by alpha_G: m_p comes from Lambda_QCD, generated by
#     the SAME anomaly (dimensional transmutation) and exponentially small without tuning. One loop, b = 7: alpha_s(M_P) from alpha_s(M_Z),
#     Lambda_QCD/M_P = exp(-2 pi / (b alpha_s(M_P))).
aZ, MZ, MP = 0.118, 91.19, 1.22e19
b = 7
inv_aP = 1 / aZ + b / (2 * np.pi) * np.log(MP / MZ)
LQ_over_MP = np.exp(-2 * np.pi * inv_aP / b)
mp_over_MP = 0.938 / MP
ok(f"PU2 REFUTED (NF4 mechanism): the anomaly gives Lambda_QCD/M_P = {LQ_over_MP:.1e} with no tuning (m_p/M_P = {mp_over_MP:.1e}); "
   "K-protected smallness is natural for marginal couplings and unnatural only for relevant operators (mu^2: dim 2, Lambda: dim 0) -- "
   "the standard Wilson/'t Hooft counting; the GA reading adds no new criterion", 1e-22 < LQ_over_MP < 1e-18)

# PU3 'fine tuning = exactly the unstable K/homothety points': the forward direction gains a fourth case, Q (density contrast grows as
#     a in the matter era: the smoothness/horizon problem); the converse fails: strong CP and the Yukawa hierarchy are smallness puzzles
#     at stable points. NARROWED: unstable point => tuning problem, not iff.
t = sp.symbols('t', positive=True); a = t**sp.Rational(2, 3); H = sp.diff(a, t) / a
growing = sp.simplify(sp.diff(t**sp.Rational(2, 3), t, 2) + 2 * H * sp.diff(t**sp.Rational(2, 3), t) - sp.Rational(3, 2) * H**2 * t**sp.Rational(2, 3))
ok(f"PU3 NARROWED: delta = a solves the matter-era growth equation (residual {growing}): Q = 0 is a repelling homothety point too "
   "(smoothness problem); strong CP and the Yukawa pattern are puzzles at stable points: the criterion is one-way", growing == 0)

# PU4 ladder step 2 of 55 ('n_inf: O(4,1) -> Sim(3)') conflates two actions: O(1,4) of de Sitter acts on spacetime, O(4,1) of 32 is the
#     conformal group of 3-space (isomorphic, physically unrelated, 32 prop. 11). The Newtonian limit of de Sitter is a CONTRACTION
#     (c -> infinity) to the Newton-Hooke group, dimension 10, not Sim(3), dimension 7. Check: boosts commute in the limit.
c, v1, v2 = sp.symbols('c v1 v2', positive=True)
K1 = sp.Matrix([[0, 1 / c**2, 0], [1, 0, 0], [0, 0, 0]])          # (t, x, y): t -> t + v x / c^2, x -> x + v t
K2 = sp.Matrix([[0, 0, 1 / c**2], [0, 0, 0], [1, 0, 0]])
comm = sp.simplify(K1 * K2 - K2 * K1)
lim = comm.applyfunc(lambda e: sp.limit(e, c, sp.oo))
ok(f"PU4 REFUTED (55 ladder step 2): [K1, K2] = {comm.tolist()} -> {lim.tolist()} as c -> oo: the limit is a contraction keeping "
   "dimension 10 (Newton-Hooke / Galilei), Sim(3) has dimension 7; the chain O(1,4) -> Sim(3) is not a subgroup chain",
   lim == sp.zeros(3, 3) and comm != sp.zeros(3, 3))


# Minimal Clifford algebra shared by ga_*_check.py (papers/restart/11, 12).
# Generators are the reciprocal frame e^mu, so A = A_mu e^mu and grad = e^mu d_mu.
import itertools
import sympy as sp

def blade_mul(a, b, sig):
    """Product of basis blades a, b (sorted tuples) -> (sign*metric factor, blade)."""
    s, lst = 1, list(a) + list(b)
    for i in range(len(lst)):              # bubble sort, count swaps
        for j in range(len(lst) - 1 - i):
            if lst[j] > lst[j + 1]:
                lst[j], lst[j + 1] = lst[j + 1], lst[j]
                s = -s
    out, i = [], 0
    while i < len(lst):                    # contract equal neighbours e^m e^m = sig[m]
        if i + 1 < len(lst) and lst[i] == lst[i + 1]:
            s *= sig[lst[i]]
            i += 2
        else:
            out.append(lst[i]); i += 1
    return s, tuple(out)

def gp(X, Y, sig):
    R = {}
    for a, ca in X.items():
        for b, cb in Y.items():
            s, c = blade_mul(a, b, sig)
            R[c] = R.get(c, 0) + s * ca * cb
    return clean(R)

def clean(X):
    return {k: sp.expand(v) for k, v in X.items() if sp.expand(v) != 0}

def grade(X, r):
    return {k: v for k, v in X.items() if len(k) == r}

def grades(X):
    return sorted({len(k) for k in X})

def add(*Xs):
    R = {}
    for X in Xs:
        for k, v in X.items():
            R[k] = R.get(k, 0) + v
    return clean(R)

def scal(c, X):
    return clean({k: c * v for k, v in X.items()})

def wedge(X, Y, sig):
    """Outer product, bilinear extension of <X_r Y_s>_{r+s}."""
    R = {}
    for r in grades(X):
        for s in grades(Y):
            R = add(R, grade(gp(grade(X, r), grade(Y, s), sig), r + s))
    return R

def ext_d(X, coords, sig):
    """grad ^ X = sum_mu e^mu ^ d_mu X  (exterior derivative)."""
    R = {}
    for m, x in enumerate(coords):
        R = add(R, wedge({(m,): 1}, {k: sp.diff(v, x) for k, v in X.items()}, sig))
    return R

def vec(comps):
    return clean({(m,): c for m, c in enumerate(comps)})

def tower(A, coords, sig):
    """Pi = (1 + A) ^ exp_wedge(F), F = grad ^ A: the whole metric-free algebra generated by A."""
    n = len(coords)
    F = ext_d(A, coords, sig)
    even, Fk = {(): 1}, {(): 1}
    for k in range(1, n // 2 + 1):
        Fk = wedge(Fk, F, sig)
        even = add(even, scal(sp.Rational(1, sp.factorial(k)), Fk))
    return add(even, wedge(A, even, sig)), F

